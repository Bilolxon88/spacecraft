import { test,expect } from '@playwright/test'

test('landing motion preserves navigation, theme, preview and page width',async({page},info)=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto('/')
 await expect(page.locator('html')).toHaveClass(/landing-smooth-scroll/)
 await expect(page.getByRole('heading',{level:1})).toBeVisible()
 await expect(page.locator('.journey-stage')).toHaveAttribute('data-rendered','true')
 await expect(page.locator('canvas')).toBeVisible()
 await page.waitForTimeout(1200)
 await page.screenshot({path:info.outputPath('desktop-landing.png')})
 await page.getByRole('link',{name:'Possibilities',exact:true}).click()
 await expect.poll(()=>page.evaluate(()=>Math.abs(document.querySelector('#possibilities')!.getBoundingClientRect().top-35))).toBeLessThan(3)
 await page.getByRole('link',{name:'Templates',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Find your starting point.'})).toBeInViewport()
 await page.waitForTimeout(1100)
 for(const card of await page.locator('.landing-templates .template-card').all())await expect(card).toBeVisible()
 expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(1440)
 await page.getByRole('button',{name:'Before',exact:true}).click()
 await expect(page.getByText('The beginning of an idea.')).toBeVisible()
 await page.getByRole('button',{name:'After',exact:true}).click()
 await expect(page.getByText('A little more you.')).toBeVisible()
 await page.getByText('Where are my projects saved?',{exact:true}).click()
 await expect(page.locator('details[open]')).toContainText('this browser on this device')
 await page.getByRole('button',{name:/Switch to .* theme/}).click()
 await page.getByRole('link',{name:'Open workspace',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Good spaces start here.'})).toBeVisible()
 await expect(page.locator('html')).not.toHaveClass(/landing-smooth-scroll/)
 expect(errors).toEqual([])
})

test('reduced motion keeps all content visible and disables parallax and smooth scrolling',async({page})=>{
 await page.emulateMedia({reducedMotion:'reduce'})
 await page.setViewportSize({width:390,height:844})
 await page.goto('/')
 await expect(page.getByRole('heading',{level:1})).toBeVisible()
 await expect(page.locator('html')).not.toHaveClass(/landing-smooth-scroll/)
 await expect(page.locator('.journey-sticky')).toHaveCSS('position','relative')
 await page.locator('#templates').scrollIntoViewIfNeeded()
 await expect(page.getByRole('heading',{name:'Find your starting point.'})).toBeVisible()
 expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
 await page.locator('.landing-templates .template-card').first().click()
 await expect(page.getByRole('heading',{name:'Make room for possibility.'})).toBeVisible()
})
