import { test, expect } from '@playwright/test'
import fs from 'node:fs/promises'

test('studio rail, actual asset editing, themes and compact panels stay connected', async ({ page }) => {
  test.setTimeout(120000)
  page.setDefaultTimeout(20000)
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/projects/new?template=living')
  await page.getByLabel('Project name').fill('Atelier living')
  await page.getByRole('spinbutton', { name: 'Width m', exact: true }).fill('5')
  await page.getByRole('button', { name: 'Open your studio' }).click()
  await page.getByRole('button', { name: 'Dismiss introduction' }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await expect.poll(() => page.locator('canvas').evaluate((canvas: HTMLCanvasElement) => Object.keys(JSON.parse(canvas.dataset.loadedModels || '{}')).length)).toBe(7)
  const rail = page.getByRole('navigation', { name: 'Studio tools' })
  await rail.getByRole('button', { name: 'Open lighting panel' }).click()
  await expect(page.getByLabel('Furniture category')).toHaveValue('Lamps')
  await rail.getByRole('button', { name: 'Open decor panel' }).click()
  await expect(page.getByLabel('Furniture category')).toHaveValue('Plants')
  await rail.getByRole('button', { name: 'Open objects panel' }).click()
  await page.getByRole('button', { name: 'Haven sofa', exact: true }).click()
  await expect(page.getByLabel('Object name')).toHaveValue('Haven sofa')
  await page.getByLabel('Width', { exact: true }).fill('2.1')
  await page.getByLabel('Width', { exact: true }).blur()
  await page.getByLabel('Furniture color', { exact: true }).fill('#a69178')
  await page.getByLabel('Furniture color', { exact: true }).blur()
  await expect.poll(() => page.locator('canvas').evaluate((canvas: HTMLCanvasElement) => {
    const models = Object.values(JSON.parse(canvas.dataset.loadedModels || '{}')) as { catalogId: string; finishes: { name: string; color: string }[]; bounds: { min: number[]; max: number[] } }[]
    const sofa = models.find(model => model.catalogId === 'sofa')
    return sofa && { width: Math.round((sofa.bounds.max[0] - sofa.bounds.min[0]) * 100), fabric: sofa.finishes.find(finish => finish.name.includes('fabric'))?.color }
  })).toEqual({ width: 210, fabric: 'a69178' })
  await page.getByRole('button', { name: 'Undo (Ctrl+Z)', exact: true }).click()
  await page.getByRole('button', { name: 'Haven sofa', exact: true }).click()
  await expect(page.getByLabel('Furniture color')).not.toHaveValue('#a69178')
  await page.getByRole('button', { name: 'Redo (Ctrl+Shift+Z)', exact: true }).click()
  await page.getByRole('button', { name: 'Haven sofa', exact: true }).click()
  await expect(page.getByLabel('Furniture color')).toHaveValue('#a69178')
  await rail.getByRole('button', { name: 'Open furniture panel' }).click()
  await fs.mkdir('docs/redesign', { recursive: true })
  await page.screenshot({ path: 'docs/redesign/editor-dark.png' })
  await page.getByRole('button', { name: 'Switch to light theme' }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await page.screenshot({ path: 'docs/redesign/editor-light.png' })
  await rail.getByRole('button', { name: 'Open room panel' }).click()
  await expect(page.getByRole('heading', { name: 'Your room', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Set floor to walnut' }).click()
  await expect(page.getByRole('button', { name: 'Set floor to walnut' })).toHaveAttribute('aria-pressed', 'true')
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.getByRole('complementary', { name: 'Furniture and scene' })).toHaveCount(0)
  await expect(page.getByRole('complementary', { name: 'Properties inspector' })).toHaveCount(0)
  await page.screenshot({ path: 'docs/redesign/editor-mobile.png' })
  await rail.getByRole('button', { name: 'Open furniture panel' }).click()
  await expect(page.getByLabel('Search furniture')).toBeVisible()
  await rail.getByRole('button', { name: 'Open room panel' }).click()
  await expect(page.getByLabel('Search furniture')).toHaveCount(0)
  await expect(page.getByRole('heading', { name: 'Your room', exact: true })).toBeVisible()
  await page.screenshot({ path: 'docs/redesign/editor-mobile-properties.png' })
  await page.keyboard.press('Escape')
  await expect(page.getByRole('complementary', { name: 'Properties inspector' })).toHaveCount(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await rail.getByRole('button', { name: 'Studio help' }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await rail.getByRole('button', { name: 'Save design' }).click()
  await expect(page.getByText('All changes saved')).toBeVisible()
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await expect(page.getByLabel('Project name')).toHaveValue('Atelier living')
  expect(errors).toEqual([])
})

test('mobile menu, inspiration filters and editorial entry links work', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await page.getByRole('button', { name: 'Open navigation', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Close navigation' })).toHaveAttribute('aria-expanded', 'true')
  await page.locator('#mobile-navigation').getByRole('link', { name: /Inspiration/ }).click()
  await expect(page.locator('#mobile-navigation')).toHaveCount(0)
  await expect(page.locator('#inspiration')).toBeInViewport()
  await page.getByRole('button', { name: 'Rest', exact: true }).click()
  await expect(page.locator('.inspiration-item')).toHaveCount(1)
  await expect(page.locator('.inspiration-item')).toHaveAttribute('href', '/projects/new?template=bedroom')
  await page.locator('.inspiration-item').click()
  await expect(page.getByRole('button', { name: 'Modern Bedroom', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.goto('/')
  await page.getByRole('button', { name: 'Open navigation', exact: true }).click()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: 'Open navigation', exact: true })).toBeFocused()
  await expect(page.locator('.journey-stage')).toHaveAttribute('data-rendered', 'true')
  await expect(page.locator('.journey-loading')).toHaveCount(0)
  await fs.mkdir('docs/redesign', { recursive: true })
  await page.screenshot({ path: 'docs/redesign/landing-mobile.png' })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.screenshot({ path: 'docs/redesign/landing-dark.png', fullPage: true })
  await page.getByRole('button', { name: 'Switch to light theme' }).click()
  await page.screenshot({ path: 'docs/redesign/landing-light.png', fullPage: true })
  await page.getByRole('link', { name: 'Explore the studio', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Scandinavian Living Room', exact: true })).toHaveAttribute('aria-pressed', 'true')
})
