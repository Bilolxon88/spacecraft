import { test, expect } from '@playwright/test'
import { journeyPose } from '../src/features/landing/journeyPath'

test('the pinned canvas camera enters through the doorway and reverses with native scroll', async ({ page }, info) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  const stage = page.locator('.journey-stage')
  await expect(stage).toHaveAttribute('data-rendered', 'true')
  await page.screenshot({ path: info.outputPath('initial-viewport.png') })
  const geometry = await page.locator('.room-journey').evaluate(element => ({ top: element.getBoundingClientRect().top + window.scrollY, distance: element.clientHeight - window.innerHeight }))
  const sample = async (progress: number) => {
    await page.evaluate(({ top, distance, p }) => window.scrollTo({ top: top + distance * p, behavior: 'instant' }), { ...geometry, p: progress })
    await expect.poll(async () => Math.abs(Number(await stage.getAttribute('data-camera-progress')) - progress)).toBeLessThan(.0005)
    const actual = (await stage.getAttribute('data-camera-position'))!.split(',').map(Number)
    const expected = journeyPose(progress).position.toArray()
    actual.forEach((value, axis) => expect(value).toBeCloseTo(expected[axis], 1))
    return actual
  }
  await sample(0)
  await page.mouse.move(1100, 500)
  await page.mouse.wheel(0, 240)
  await expect.poll(() => page.evaluate(() => window.scrollY)).toBeGreaterThan(geometry.top + 100)
  await sample(0)
  await page.screenshot({ path: info.outputPath('01-exterior.png') })
  await sample(.4)
  await page.screenshot({ path: info.outputPath('02-approach.png') })
  await sample(.55)
  await page.screenshot({ path: info.outputPath('03-entrance.png') })
  const inside = await sample(.8)
  expect(inside[1]).toBe(1.65)
  expect(inside[2]).toBeLessThan(2.5)
  await page.screenshot({ path: info.outputPath('04-interior.png') })
  const first = await sample(.6)
  await sample(1)
  await page.screenshot({ path: info.outputPath('05-detail.png') })
  const reversed = await sample(.6)
  reversed.forEach((value, axis) => expect(value).toBeCloseTo(first[axis], 1))
  await sample(0)
  await sample(.7)
  expect(await page.locator('.journey-sticky').evaluate(element => element.getBoundingClientRect().top)).toBeCloseTo(0, 0)
  await page.locator('.journey-skip').click()
  await expect(page.locator('#possibilities')).toBeInViewport()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(1440)
  expect(errors).toEqual([])
})

test('mobile scrolling reaches the interior and reduced motion removes pinning and travel', async ({ page }, info) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  const stage = page.locator('.journey-stage')
  await expect(stage).toHaveAttribute('data-rendered', 'true')
  await page.locator('.room-journey').evaluate(element => window.scrollTo({ top: element.getBoundingClientRect().top + window.scrollY + (element.clientHeight - window.innerHeight) * .85, behavior: 'instant' }))
  await expect.poll(async () => Number(await stage.getAttribute('data-camera-progress'))).toBeGreaterThan(.849)
  await page.screenshot({ path: info.outputPath('mobile-interior.png') })
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(page.locator('.room-journey')).toHaveClass(/journey-reduced/)
  await expect(page.locator('.journey-sticky')).toHaveCSS('position', 'relative')
  await expect(stage).toHaveAttribute('data-camera-progress', '0.0000')
  await expect(page.locator('.journey-skip')).toHaveCount(0)
  await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }))
  await expect(page.getByRole('link', { name: 'Start creating' })).toBeVisible()
  await page.screenshot({ path: info.outputPath('mobile-reduced-motion.png') })
})
